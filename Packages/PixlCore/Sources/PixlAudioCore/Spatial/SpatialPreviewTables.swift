// The coefficient tables of the on-device spatial stage (cloud audio spec of 2026-11-10, section 7), decoded from
// `spatial_preview_v1.json`. The worker generates that file (`python -m pixl_worker.spatial.preview`), both apps
// carry byte-identical copies, and nobody edits it by hand. This file only reads it: the stage itself (the crossover,
// the two FIRs, the sparse room, the ramps) lives next to it and is checked against `spatial_preview_golden_v1.json`.
//
// Decoding allocates and takes a moment (the file is about 70 KB of numbers): do it once, off the main thread and
// never on the audio thread, and hand the stage plain buffers copied from these arrays.

import Foundation
import PixlModel

/// One sparse room tap: the high band of the left and right inputs, `delay` samples ago, added to one ear.
public struct SpatialSparseTap: Sendable, Hashable {
    public let delay: Int
    public let gainFromLeft: Double
    public let gainFromRight: Double

    public init(delay: Int, gainFromLeft: Double, gainFromRight: Double) {
        self.delay = delay
        self.gainFromLeft = gainFromLeft
        self.gainFromRight = gainFromRight
    }
}

/// The table of one profile at one sample rate. With `x` the stereo input:
///
///     lo = LR4_lowpass(x, xoverHz)        two identical RBJ low-pass biquads (Q = 1/√2) in series, per channel
///     hi = x - lo
///     yL = fir(hiL, direct) + fir(hiR, cross) + Σ sparseL: gainFromLeft·hiL[n-d] + gainFromRight·hiR[n-d]
///     yR = fir(hiR, direct) + fir(hiL, cross) + Σ sparseR: gainFromLeft·hiL[n-d] + gainFromRight·hiR[n-d]
///     out = gain · (y + lo[n - lowDelay])                         fir(x, h)[n] = Σ h[k]·x[n-k]
public struct SpatialPreviewTable: Sendable, Hashable {
    /// The crossover frequency (the biquad coefficients are computed on the device from it and the rate).
    public let xoverHz: Double
    /// The delay of the low band, in samples (it lines the untouched lows up with the centre's arrival).
    public let lowDelay: Int
    /// The length of `direct` and `cross`.
    public let taps: Int
    /// The same-side FIR.
    public let direct: [Double]
    /// The other-side FIR.
    public let cross: [Double]
    /// The sparse room of the left ear.
    public let sparseL: [SpatialSparseTap]
    /// The sparse room of the right ear (different on purpose: that is what surrounds a centred voice).
    public let sparseR: [SpatialSparseTap]
    /// The output gain: the loudness match and the table file's headroom together.
    public let gain: Double

    public init(xoverHz: Double, lowDelay: Int, taps: Int, direct: [Double], cross: [Double],
                sparseL: [SpatialSparseTap], sparseR: [SpatialSparseTap], gain: Double) {
        self.xoverHz = xoverHz
        self.lowDelay = lowDelay
        self.taps = taps
        self.direct = direct
        self.cross = cross
        self.sparseL = sparseL
        self.sparseR = sparseR
        self.gain = gain
    }

    /// The longest sparse delay of this table.
    public var maxSparseDelay: Int {
        max(sparseL.map(\.delay).max() ?? 0, sparseR.map(\.delay).max() ?? 0)
    }

    /// The history this table reads, in samples: enough for the FIRs, the low band's delay and the sparse room.
    public var maxDelay: Int { max(maxSparseDelay, taps - 1, lowDelay) }
}

/// Why a table file was refused.
public enum SpatialPreviewError: Error, Sendable, Hashable {
    /// Not JSON of the expected shape.
    case unreadable(String)
    case wrongSchema(String)
    case unsupportedVersion(Int)
    /// The file was generated by another render engine than this build knows.
    case wrongEngine(String)
    case missingProfile(String)
    case missingRate(profile: String, rate: Int)
    /// A table's numbers do not hold together (the detail says what).
    case malformedTable(profile: String, rate: Int, detail: String)
}

/// Every table of the file: six profiles at 44.1 and 48 kHz.
public struct SpatialPreviewTables: Sendable, Hashable {
    public static let schemaName = "pixl.spatial.preview"
    public static let schemaVersion = 1
    /// The rates the stage runs at. At any other rate it is bypassed.
    public static let sampleRates: [Int] = [44_100, 48_000]
    /// The resource's name in both apps (`spatial_preview_v1.json`).
    public static let resourceName = "spatial_preview_v1"
    public static let resourceExtension = "json"

    /// The render engine the tables were generated by (`pixl-spatial-1`).
    public let engine: String
    /// The headroom built into every `gain` (4.0): what the level rule gives back while the stage is audible.
    public let headroomDb: Double
    private let tables: [SpatialProfile: [Int: SpatialPreviewTable]]

    public init(engine: String, headroomDb: Double, tables: [SpatialProfile: [Int: SpatialPreviewTable]]) {
        self.engine = engine
        self.headroomDb = headroomDb
        self.tables = tables
    }

    /// The table of `profile` at `sampleRate` (44100 or 48000), or nil at any other rate: the stage is then bypassed.
    public func table(for profile: SpatialProfile, sampleRate: Int) -> SpatialPreviewTable? {
        tables[profile]?[sampleRate]
    }

    /// The same for a rate as the audio system reports it (within half a hertz of a supported rate).
    public func table(for profile: SpatialProfile, sampleRate: Double) -> SpatialPreviewTable? {
        guard let rate = Self.supportedRate(sampleRate) else { return nil }
        return table(for: profile, sampleRate: rate)
    }

    /// 44100 or 48000 when `sampleRate` is one of them (within half a hertz), else nil.
    public static func supportedRate(_ sampleRate: Double) -> Int? {
        sampleRates.first { abs(Double($0) - sampleRate) <= 0.5 }
    }

    /// The longest history any table reads (about 8600 samples: Concert Hall at 48 kHz).
    public var maxDelay: Int {
        tables.values.flatMap(\.values).map(\.maxDelay).max() ?? 0
    }

    /// The size of the one delay ring that serves every table: the smallest power of two that is at least the longest
    /// history plus one, so a change of profile never needs a new ring.
    public var ringCapacity: Int {
        var capacity = 1
        while capacity < maxDelay + 1 { capacity <<= 1 }
        return capacity
    }

    // MARK: Decoding

    private struct Wire: Decodable {
        var schema: String
        var v: Int
        var engine: String
        var headroomDb: Double
        var profiles: [String: [String: WireTable]]
    }

    private struct WireTable: Decodable {
        var xoverHz: Double
        var lowDelay: Int
        var taps: Int
        var direct: [Double]
        var cross: [Double]
        var sparseL: [[Double]]
        var sparseR: [[Double]]
        var gain: Double
    }

    /// Decodes and checks the file. Every profile of this build must be there at both rates (profiles the build does
    /// not know are skipped), every FIR must have `taps` values, and every number must be usable.
    public static func decode(_ data: Data) throws -> SpatialPreviewTables {
        let wire: Wire
        do {
            wire = try JSONDecoder().decode(Wire.self, from: data)
        } catch {
            throw SpatialPreviewError.unreadable(String(describing: error))
        }
        guard wire.schema == schemaName else { throw SpatialPreviewError.wrongSchema(wire.schema) }
        guard wire.v == schemaVersion else { throw SpatialPreviewError.unsupportedVersion(wire.v) }
        guard wire.engine == CloudLibrary.engineId else { throw SpatialPreviewError.wrongEngine(wire.engine) }
        guard wire.headroomDb.isFinite, wire.headroomDb >= 0 else {
            throw SpatialPreviewError.unreadable("headroomDb \(wire.headroomDb)")
        }
        var tables: [SpatialProfile: [Int: SpatialPreviewTable]] = [:]
        for profile in SpatialProfile.allCases {
            guard let rates = wire.profiles[profile.rawValue] else {
                throw SpatialPreviewError.missingProfile(profile.rawValue)
            }
            var byRate: [Int: SpatialPreviewTable] = [:]
            for rate in sampleRates {
                guard let table = rates[String(rate)] else {
                    throw SpatialPreviewError.missingRate(profile: profile.rawValue, rate: rate)
                }
                byRate[rate] = try checked(table, profile: profile.rawValue, rate: rate)
            }
            tables[profile] = byRate
        }
        return SpatialPreviewTables(engine: wire.engine, headroomDb: wire.headroomDb, tables: tables)
    }

    private static func checked(_ wire: WireTable, profile: String, rate: Int) throws -> SpatialPreviewTable {
        func fail(_ detail: String) -> SpatialPreviewError {
            .malformedTable(profile: profile, rate: rate, detail: detail)
        }
        guard wire.xoverHz.isFinite, wire.xoverHz > 0, wire.xoverHz < Double(rate) / 2 else { throw fail("xoverHz") }
        guard wire.taps > 0, wire.direct.count == wire.taps, wire.cross.count == wire.taps else { throw fail("taps") }
        guard wire.lowDelay >= 0, wire.lowDelay < wire.taps else { throw fail("lowDelay") }
        guard wire.gain.isFinite, wire.gain > 0 else { throw fail("gain") }
        guard wire.direct.allSatisfy(\.isFinite), wire.cross.allSatisfy(\.isFinite) else { throw fail("taps values") }
        // Ten seconds is far beyond any room here (the longest is under 0.2 s): a larger delay is a broken file.
        let longest = Double(rate) * 10
        func sparse(_ rows: [[Double]], _ name: String) throws -> [SpatialSparseTap] {
            try rows.map { row in
                guard row.count == 3, row.allSatisfy(\.isFinite), row[0] >= 0, row[0] <= longest,
                      row[0] == row[0].rounded() else { throw fail(name) }
                return SpatialSparseTap(delay: Int(row[0]), gainFromLeft: row[1], gainFromRight: row[2])
            }
        }
        return SpatialPreviewTable(xoverHz: wire.xoverHz, lowDelay: wire.lowDelay, taps: wire.taps, direct: wire.direct,
                                   cross: wire.cross, sparseL: try sparse(wire.sparseL, "sparseL"),
                                   sparseR: try sparse(wire.sparseR, "sparseR"), gain: wire.gain)
    }
}

/// `spatial_preview_golden_v1.json`: a fixed input and the reference implementation's output for it, from a zero
/// state, for every profile and rate. The stage's unit tests must reproduce every output within `tolerance`.
public struct SpatialPreviewGolden: Sendable {
    public static let schemaName = "pixl.spatial.preview.golden"
    public static let resourceName = "spatial_preview_golden_v1"

    public struct Channels: Sendable, Hashable, Decodable {
        public let left: [Double]
        public let right: [Double]
    }

    /// The number of frames of the input and of every output (1024).
    public let frames: Int
    /// The largest difference allowed, per sample (1e-4).
    public let tolerance: Double
    public let input: Channels
    private let outputs: [String: [String: Channels]]

    /// The reference output for `profile` at `sampleRate`, or nil when the file has none.
    public func output(for profile: SpatialProfile, sampleRate: Int) -> Channels? {
        outputs[profile.rawValue]?[String(sampleRate)]
    }

    private struct Wire: Decodable {
        var schema: String?
        var frames: Int
        var tolerance: Double
        var input: Channels
        var output: [String: [String: Channels]]
    }

    /// Decodes and checks the file: every channel has `frames` values.
    public static func decode(_ data: Data) throws -> SpatialPreviewGolden {
        let wire: Wire
        do {
            wire = try JSONDecoder().decode(Wire.self, from: data)
        } catch {
            throw SpatialPreviewError.unreadable(String(describing: error))
        }
        if let schema = wire.schema, schema != schemaName { throw SpatialPreviewError.wrongSchema(schema) }
        guard wire.frames > 0, wire.tolerance > 0, wire.input.left.count == wire.frames,
              wire.input.right.count == wire.frames else {
            throw SpatialPreviewError.unreadable("golden input")
        }
        for (profile, rates) in wire.output {
            for (rate, channels) in rates where channels.left.count != wire.frames || channels.right.count != wire.frames {
                throw SpatialPreviewError.malformedTable(profile: profile, rate: Int(rate) ?? 0, detail: "golden output")
            }
        }
        return SpatialPreviewGolden(frames: wire.frames, tolerance: wire.tolerance, input: wire.input, outputs: wire.output)
    }
}
