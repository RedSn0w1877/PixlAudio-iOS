// Generates Packages/PixlCore/Sources/PixlNet/AI/AiPromptTemplates.swift from the Android app's
// data/ai/AiSystemPromptEngine.kt (read-only). Every Kotlin raw string ("""…""") becomes a Swift function that
// rebuilds the exact runtime string — template values interpolated first, then Kotlin `trimIndent()` (ported in
// AiPromptEngine.swift) — so indentation quirks of interpolated multi-line values are reproduced byte for byte.
//
//   node tools/android-reference/gen-ai-prompts.js <android repo root> <ios repo root>
const fs = require('fs');
const path = require('path');

const [androidRoot, iosRoot] = process.argv.slice(2);
const src = fs.readFileSync(path.join(androidRoot,
  'app/src/main/java/com/theveloper/pixelplay/data/ai/AiSystemPromptEngine.kt'), 'utf8').replace(/\r\n/g, '\n');
const lines = src.split('\n');

function camel(upper) {
  return upper.toLowerCase().replace(/_([a-z])/g, (_, c) => c.toUpperCase());
}
function swiftLiteral(s) {
  return '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n') + '"';
}

const blocks = [];
for (let i = 0; i < lines.length; i++) {
  const line = lines[i];
  if (!/"""\s*$/.test(line) || /^\s*"""/.test(line)) continue;
  let name;
  let m;
  if ((m = line.match(/val\s+([A-Za-z_]+)\s*=\s*"""/))) name = m[1].replace(/^UNIVERSAL_CONSTRAINTS$/, 'universalConstraints');
  else if ((m = line.match(/AiSystemPromptType\.([A-Z_]+)\s*->\s*"""/))) name = camel(m[1]) + 'Layer';
  else continue;
  let j = i + 1;
  while (!/^\s*"""/.test(lines[j])) j++;
  const closingIndent = lines[j].match(/^(\s*)/)[1];
  // Kotlin value: newline after the opening quotes, the lines, newline, then the closing line's indent.
  const value = '\n' + lines.slice(i + 1, j).join('\n') + '\n' + closingIndent;
  blocks.push({ name, value });
  i = j;
}
// The context layer is the bare `"""` that starts inside `if (context.isNotBlank())`.
for (let i = 0; i < lines.length; i++) {
  if (/^\s*"""\s*$/.test(lines[i]) && lines[i - 1] && /context\.isNotBlank\(\)/.test(lines[i - 1])) {
    let j = i + 1;
    while (!/^\s*"""/.test(lines[j])) j++;
    const closingIndent = lines[j].match(/^(\s*)/)[1];
    blocks.push({ name: 'contextLayer', value: '\n' + lines.slice(i + 1, j).join('\n') + '\n' + closingIndent });
  }
}

let out = `// GENERATED by tools/android-reference/gen-ai-prompts.js from the Android app's AiSystemPromptEngine.kt.
// Do not edit by hand: each function rebuilds a Kotlin raw string exactly (template values first, then
// Kotlin trimIndent()), so the prompts are byte-identical to Android's.

enum AiPromptTemplates {
`;
for (const b of blocks) {
  const parts = [];
  const params = [];
  const re = /\$([A-Za-z_][A-Za-z0-9_]*)/g;
  let last = 0;
  let m;
  while ((m = re.exec(b.value))) {
    parts.push(swiftLiteral(b.value.slice(last, m.index)));
    parts.push(m[1]);
    if (!params.includes(m[1])) params.push(m[1]);
    last = m.index + m[0].length;
  }
  parts.push(swiftLiteral(b.value.slice(last)));
  const body = parts.filter(p => p !== '""').join(' + ');
  if (params.length === 0) {
    out += `    static let ${b.name} = KotlinIndent.trimIndent(${body})\n\n`;
  } else {
    out += `    static func ${b.name}(${params.map(p => `${p}: String`).join(', ')}) -> String {\n`;
    out += `        KotlinIndent.trimIndent(${body})\n    }\n\n`;
  }
}
out = out.replace(/\n\n$/, '\n') + '}\n';
const target = path.join(iosRoot, 'Packages/PixlCore/Sources/PixlNet/AI/AiPromptTemplates.swift');
fs.writeFileSync(target, out, 'utf8');
console.log(`wrote ${blocks.length} templates to ${target}`);
