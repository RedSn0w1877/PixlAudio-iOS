#!/usr/bin/env python3
"""Shipped tables of the music brain, Swift side (docs/brain-spec.md, 10.3 rule 15 and 10.5).

    python tools/brain/gen_tables.py

Writes Packages/PixlCore/Sources/PixlLibrary/Brain/FoldTable.swift and TitleRules.swift from the two
reviewed tables in Packages/PixlCore/Tests/PixlLibraryTests/Fixtures/brain/ (fold-v1.tsv and
title-rules-v1.tsv). Those two files are copies of the Android repo's brain/tables/*.tsv: copy them
again from there when they change, never edit them here, then run this script. BrainTablesInSyncTests
fails when the generated Swift and the .tsv files disagree.

fold-v1.tsv:        <code point, hex> TAB <replacement, space-separated hex code points; empty = delete>
title-rules-v1.tsv: <kind> TAB <token sequence>
"""
import os

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
TABLES = os.path.join(ROOT, "Packages", "PixlCore", "Tests", "PixlLibraryTests", "Fixtures", "brain")
OUT = os.path.join(ROOT, "Packages", "PixlCore", "Sources", "PixlLibrary", "Brain")

FLAG_NAMES = ["live", "remix", "acoustic", "instrumental", "remaster", "cover", "karaoke", "sped-up", "slowed",
              "re-recorded"]


def read_fold():
    rows = []
    with open(os.path.join(TABLES, "fold-v1.tsv"), encoding="ascii") as f:
        for line in f:
            line = line.rstrip("\r\n")
            if not line or line.startswith("#"):
                continue
            key, _, value = line.partition("\t")
            rows.append((int(key, 16), [int(h, 16) for h in value.split()]))
    rows.sort()
    for cp, _ in rows:
        if cp > 0xFFFF:
            raise SystemExit("fold-v1 keys must be in the BMP: %X" % cp)
    return rows


def read_rules():
    rules = []
    with open(os.path.join(TABLES, "title-rules-v1.tsv"), encoding="ascii") as f:
        for line in f:
            line = line.rstrip("\r\n")
            if not line or line.startswith("#"):
                continue
            kind, _, tokens = line.partition("\t")
            rules.append((kind.strip(), tokens.strip()))
    return rules


def wrap(items, per_line, indent="        "):
    lines = []
    for i in range(0, len(items), per_line):
        lines.append(indent + ", ".join(items[i:i + per_line]) + ",")
    return lines


def swift_string(text):
    for c in text:
        if not (0x20 <= ord(c) < 0x7F) or c == '"' or ord(c) == 92:
            raise SystemExit("title rules must be plain ASCII without quotes: %r" % text)
    return '"%s"' % text


def main():
    rows = read_fold()
    offsets = [0]
    scalars = []
    for _, value in rows:
        scalars.extend(value)
        offsets.append(len(scalars))
    lines = [
        "// GENERATED by tools/brain/gen_tables.py from Tests/PixlLibraryTests/Fixtures/brain/fold-v1.tsv. Do not edit.",
        "",
        "/// fold-v1 (docs/brain-spec.md, 10.5): the non-ASCII rows of `BrainText.fold`, sorted by key.",
        "enum FoldTable {",
        "    static let version = 1",
        "    static let rows = %d" % len(rows),
        "",
        "    /// One scalar of the Basic Multilingual Plane per row, ascending.",
        "    static let keys: [UInt16] = [",
    ]
    lines += wrap(["0x%04X" % cp for cp, _ in rows], 12)
    lines += [
        "    ]",
        "",
        "    /// Where each row's replacement starts in `values`; one extra entry closes the last row. A row whose two",
        "    /// offsets are equal deletes the scalar.",
        "    static let offsets: [UInt16] = [",
    ]
    lines += wrap([str(o) for o in offsets], 20)
    lines += [
        "    ]",
        "",
        "    /// The replacement scalars of every row, in key order.",
        "    static let values: [UInt16] = [",
    ]
    for s in scalars:
        if s > 0xFFFF:
            raise SystemExit("fold-v1 replacements must be in the BMP: %X" % s)
    lines += wrap(["0x%04X" % s for s in scalars], 12)
    lines += ["    ]", "}", ""]
    with open(os.path.join(OUT, "FoldTable.swift"), "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))

    rules = read_rules()
    unknown = [k for k, _ in rules if k not in FLAG_NAMES and k not in ("neutral-prefix", "neutral-equals")]
    if unknown:
        raise SystemExit("unknown rule kinds: %s" % unknown)
    flags = [(k, t) for k, t in rules if k in FLAG_NAMES]
    lines = [
        "// GENERATED by tools/brain/gen_tables.py from Tests/PixlLibraryTests/Fixtures/brain/title-rules-v1.tsv. Do not edit.",
        "",
        "/// title-rules-v1 (docs/brain-spec.md, 10.5), in file order. Token sequences are already folded.",
        "enum TitleRules {",
        "    static let version = 1",
        "",
        "    /// Flag rules: the bit index into versionFlags, then the token sequence a segment must contain.",
        "    static let flagBits: [Int32] = [%s]" % ", ".join(str(FLAG_NAMES.index(k)) for k, _ in flags),
        "    static let flagTokens: [String] = [",
    ]
    lines += ["        %s," % swift_string(t) for _, t in flags]
    lines += [
        "    ]",
        "",
        "    /// Neutral rules: a segment that starts with one of these token sequences is dropped without a flag.",
        "    static let neutralPrefix: [String] = [",
    ]
    lines += ["        %s," % swift_string(t) for k, t in rules if k == "neutral-prefix"]
    lines += [
        "    ]",
        "",
        "    /// Neutral rules: a segment equal to one of these token sequences is dropped without a flag.",
        "    static let neutralEquals: [String] = [",
    ]
    lines += ["        %s," % swift_string(t) for k, t in rules if k == "neutral-equals"]
    lines += ["    ]", "}", ""]
    with open(os.path.join(OUT, "TitleRules.swift"), "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))
    print("FoldTable.swift: %d rows, %d replacement scalars; TitleRules.swift: %d rules" % (len(rows), len(scalars), len(rules)))


if __name__ == "__main__":
    main()
