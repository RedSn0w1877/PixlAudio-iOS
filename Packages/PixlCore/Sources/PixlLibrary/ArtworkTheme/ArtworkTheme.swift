// Album-art colour theming, ported from the Android app's `ui/theme/ColorRoles.kt` (seed extraction and scheme
// generation) and `data/preferences/AlbumArtPaletteStyle.kt` / `AlbumArtColorAccuracy.kt`. The colour science
// underneath (CAM16/HCT, tonal palettes, the Celebi quantizer and the dynamic-colour role rules) is a Swift port of
// Google's Apache-2.0 colour utilities that Android ships inside `com.google.android.material:material` 1.14.0
// (`color/utilities`); see THIRD_PARTY_NOTICES.md. Golden vectors from the real Android classes live in
// Tests/PixlLibraryTests/Fixtures/theme-golden.jsonl (generated by tools/android-reference/ThemeGen.java).
//
// Everything here is pure value maths: no CoreGraphics. The app decodes a ≤128 px thumbnail with ImageIO and passes
// its pixels as ARGB (Android's `Bitmap.getPixels` layout).

import Foundation

/// The palette style setting (Android `AlbumArtPaletteStyle`, stored under `album_art_palette_style_v1`).
public enum ArtworkPaletteStyle: String, Sendable, Hashable, Codable, CaseIterable {
    case tonalSpot = "tonal_spot"
    case vibrant = "vibrant"
    case expressive = "expressive"
    case fruitSalad = "fruit_salad"

    /// Android `AlbumArtPaletteStyle.default`.
    public static let `default`: ArtworkPaletteStyle = .tonalSpot

    /// Persisted value (Android `storageKey`).
    public var storageKey: String { rawValue }

    /// Android `label`.
    public var label: String {
        switch self {
        case .tonalSpot: "Tonal Spot"
        case .vibrant: "Vibrant"
        case .expressive: "Expressive"
        case .fruitSalad: "Fruit Salad"
        }
    }

    /// Android `fromStorageKey`: unknown or missing values fall back to the default.
    public static func fromStorageKey(_ value: String?) -> ArtworkPaletteStyle {
        guard let value, let style = ArtworkPaletteStyle(rawValue: value) else { return .default }
        return style
    }
}

/// The colour-accuracy setting (Android `AlbumArtColorAccuracy`, stored under `album_art_color_accuracy_v1`).
public enum ArtworkColorAccuracy {
    public static let min = 0
    public static let max = 10
    public static let `default` = min
    public static let steps = max - min - 1

    public static func clamp(_ value: Int) -> Int { Swift.min(Swift.max(value, min), max) }
}

