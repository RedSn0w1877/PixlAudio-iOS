// Pure rules of the new UI's playlist page (stage 5, mockup `iOSPlaylist`), next to `HeroHeader` (the hero geometry it
// shares with the artist page):
//
// - `art`: what fills the hero — the playlist's own image, else its colour cover, else the first song's cover (the
//   collage the library row shows can't be one full-bleed picture), else a placeholder.
// - `owner` / `ownerLabel`: the owner line ("Made by Taizo" for generated playlists, "From Spotify" for imported ones;
//   nothing for the user's own — the page is theirs).
// - `meta`: the line under the title, "Made by Taizo · 30 Songs · 1 h 52 min".
// - `PullToFind`: when pulling the page down opens Find in playlist and scrolling closes it again, as discrete zones so
//   the scroll observer acts only when the zone changes, never per frame.

import Foundation

public enum PlaylistHero {
    /// What fills the hero.
    public enum Art: Sendable, Equatable {
        /// The playlist's own image (a URI string, as stored).
        case image(String)
        /// The playlist's colour + icon cover (no image).
        case colour
        /// A song's cover (the first song in the playlist's own order that has one).
        case songCover(String)
        /// Nothing to show: a placeholder.
        case placeholder

        /// The URI the page themes itself from and blurs, if any.
        public var uri: String? {
            switch self {
            case .image(let uri), .songCover(let uri): uri
            case .colour, .placeholder: nil
            }
        }
    }

    /// Mirrors the cover's own priority (`PlaylistCoverArt`: image, then colour), then the first song cover in
    /// `songArt` (in the playlist's order, so re-sorting the list never swaps the hero). Blank strings count as none.
    public static func art<S: Sequence>(coverImageUri: String?, hasColourCover: Bool, songArt: S) -> Art
        where S.Element == String? {
        if let image = nonBlank(coverImageUri) { return .image(image) }
        if hasColourCover { return .colour }
        for uri in songArt {
            if let cover = nonBlank(uri) { return .songCover(cover) }
        }
        return .placeholder
    }

    /// Who made the playlist, when it isn't the user.
    public enum Owner: Sendable, Equatable {
        /// Generated by the app's assistant (`isAiGenerated`).
        case taizo
        /// Imported from Spotify (`source == "SPOTIFY"`).
        case spotify
    }

    /// Generated wins over imported (a generated playlist is never re-imported); the user's own playlists have none.
    public static func owner(isAiGenerated: Bool, source: String) -> Owner? {
        if isAiGenerated { return .taizo }
        if source.caseInsensitiveCompare("SPOTIFY") == .orderedSame { return .spotify }
        return nil
    }

    public static func ownerLabel(_ owner: Owner) -> String {
        switch owner {
        case .taizo: "Made by Taizo"
        case .spotify: "From Spotify"
        }
    }

    /// "Made by Taizo · 30 Songs · 1 h 52 min": the owner (if any), the song count in the app's wording, and the
    /// total duration (left out when blank or for an empty playlist).
    public static func meta(owner: Owner?, songCount: Int, duration: String) -> String {
        var parts: [String] = []
        if let owner { parts.append(ownerLabel(owner)) }
        let count = max(0, songCount)
        parts.append(count == 1 ? "1 Song" : "\(count) Songs")
        if count > 0, let duration = nonBlank(duration) { parts.append(duration) }
        return parts.joined(separator: " · ")
    }

    private static func nonBlank(_ value: String?) -> String? {
        guard let value, !value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        return value
    }
}

/// Pull the page down past its top to reveal Find in playlist; scroll the page down to put an unused field away.
public enum PullToFind {
    /// How far past the top the page must be pulled to open the field.
    public static let openPull: Double = 72
    /// How far the page must be scrolled for an empty field to go away.
    public static let closeScroll: Double = 60

    /// Where the page's offset is (`contentOffset.y + contentInsets.top`: negative while pulled down).
    public enum Zone: Sendable, Equatable {
        case pulled
        case resting
        case scrolled
    }

    public static func zone(offset: Double) -> Zone {
        guard offset.isFinite else { return .resting }
        if offset < -openPull { return .pulled }
        if offset > closeScroll { return .scrolled }
        return .resting
    }

    public enum Action: Sendable, Equatable {
        case open
        case close
    }

    /// Entering `zone`: pulled opens a closed field (not while reordering or removing songs); scrolled closes an open
    /// field with nothing typed (a query keeps it, so its results stay reachable).
    public static func action(entering zone: Zone, isOpen: Bool, hasQuery: Bool, isEditing: Bool) -> Action? {
        switch zone {
        case .pulled: (!isOpen && !isEditing) ? .open : nil
        case .scrolled: (isOpen && !hasQuery) ? .close : nil
        case .resting: nil
        }
    }
}
