    /// Builds roles from `roleNames`-ordered values (48 entries). Nil on a wrong count.
    public init?(values: [UInt32]) {
        guard values.count == ColorRoles.roleNames.count else { return nil }
        var i = 0
        func next() -> UInt32 { defer { i += 1 }; return values[i] }
        primary = next(); onPrimary = next(); primaryContainer = next(); onPrimaryContainer = next()
        inversePrimary = next()
        secondary = next(); onSecondary = next(); secondaryContainer = next(); onSecondaryContainer = next()
