        tertiaryFixed = next(); tertiaryFixedDim = next(); onTertiaryFixed = next(); onTertiaryFixedVariant = next()
    }

    /// Applies `transform` to every role.
    public func map(_ transform: (UInt32) -> UInt32) -> ColorRoles {
        ColorRoles(values: values.map(transform))!
    }
}

/// A light and a dark scheme derived from one seed (Android `ColorSchemePair`).
public struct ColorRolesPair: Sendable, Hashable, Codable {
    public var light: ColorRoles
    public var dark: ColorRoles

    public init(light: ColorRoles, dark: ColorRoles) {
        self.light = light
        self.dark = dark
    }

    public func roles(dark isDark: Bool) -> ColorRoles { isDark ? dark : light }
}

/// Seed extraction and scheme generation (Android `extractSeedColor` / `generateColorSchemeFromSeed`).
public enum ArtworkTheme {
    /// Android's `ColorExtractionConfig.downscaleMaxDimension`: decode artwork at most this many pixels per side.
    public static let extractionMaxDimension = 128

    /// Android `ColorSchemeProcessor.CACHE_ALGORITHM_VERSION`: part of every cache key.
    public static let cacheAlgorithmVersion = "algo_v7"

    /// The scheme cache key suffix Android stores in `album_art_themes.paletteStyle`
    /// (`<style>|accuracy_<n>|algo_v7`).
    public static func paletteCacheKey(style: ArtworkPaletteStyle, accuracyLevel: Int) -> String {
        "\(style.storageKey)|accuracy_\(ArtworkColorAccuracy.clamp(accuracyLevel))|\(cacheAlgorithmVersion)"
    }

    /// The seed colour of an image given as ARGB pixels (`Bitmap.getPixels` layout, non-premultiplied), already
    /// downscaled to at most `extractionMaxDimension` per side. Android `selectSeedColorArgbFromPixels`.
    public static func seedColor(argbPixels: [UInt32], accuracyLevel: Int = ArtworkColorAccuracy.default) -> UInt32 {
        SeedColorSelector.select(pixels: argbPixels, accuracyLevel: accuracyLevel)
    }

    /// Convenience for RGBA8 buffers (row-major, `bytesPerRow` ≥ 4·width). Premultiplied pixels are
    /// un-premultiplied first, so the result matches a non-premultiplied Android bitmap.
    public static func seedColor(rgba: [UInt8], width: Int, height: Int, bytesPerRow: Int? = nil,
                                 premultipliedAlpha: Bool = true,
                                 accuracyLevel: Int = ArtworkColorAccuracy.default) -> UInt32 {
        seedColor(argbPixels: argbPixels(rgba: rgba, width: width, height: height, bytesPerRow: bytesPerRow,
                                         premultipliedAlpha: premultipliedAlpha),
                  accuracyLevel: accuracyLevel)
    }

    /// Converts an RGBA8 buffer to ARGB pixels.
    public static func argbPixels(rgba: [UInt8], width: Int, height: Int, bytesPerRow: Int? = nil,
                                  premultipliedAlpha: Bool = true) -> [UInt32] {
        let stride = bytesPerRow ?? width * 4
        guard width > 0, height > 0, stride >= width * 4, rgba.count >= stride * (height - 1) + width * 4 else {
            return []
        }
        var out = [UInt32]()
        out.reserveCapacity(width * height)
        for y in 0..<height {
            var o = y * stride
            for _ in 0..<width {
                var r = UInt32(rgba[o]), g = UInt32(rgba[o + 1]), b = UInt32(rgba[o + 2])
                let a = UInt32(rgba[o + 3])
                if premultipliedAlpha, a > 0, a < 255 {
                    r = min(255, (r * 255 + a / 2) / a)
                    g = min(255, (g * 255 + a / 2) / a)
                    b = min(255, (b * 255 + a / 2) / a)
                }
                out.append(a << 24 | r << 16 | g << 8 | b)
                o += 4
            }
        }
        return out
    }

    /// Light and dark schemes for a seed (Android `generateColorSchemeFromSeed`): near-grey seeds give grey
    /// schemes; anything that fails falls back to `ArtworkTheme.fallbackPair`.
    public static func schemePair(seed: UInt32, style: ArtworkPaletteStyle = .default) -> ColorRolesPair {
        SchemeBuilder.pair(seed: seed, style: style)
    }

    /// Android `generateMonochromeColorSchemeFromSeed`.
    public static func monochromePair(seed: UInt32) -> ColorRolesPair {
        SchemeBuilder.monochromePair(seed: seed)
    }

    /// The seed of PixlAudio's own palette (Android `LightPrimary`, `0xFF6C4FF5`). iOS has no wallpaper colours, so
    /// the app chrome is themed from this seed where Android would use the system's dynamic scheme.
    public static let brandSeed: UInt32 = 0xFF6C_4FF5

    /// The tonal-spot pair of `brandSeed`.
    public static let brandPair: ColorRolesPair = schemePair(seed: brandSeed)

    /// The app-wide accent scheme of a picked colour (iOS-only, owner request 2026-10-07: Settings › Appearance ›
    /// Accent Color). TonalSpot surfaces and role tones with the primary at the seed's own chroma (at least 36), so a
    /// vivid pick stays vivid in light mode and every role keeps its contrast. Near-grey seeds give grey schemes.
    /// The default accent is `brandPair`, not `accentPair(seed: brandSeed)`, so nothing changes until a colour is
    /// picked.
    public static func accentPair(seed: UInt32) -> ColorRolesPair {
        SchemeBuilder.accentPair(seed: seed)
    }
}
